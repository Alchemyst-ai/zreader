/**
 * `zreader/sw` — offline reading (opt-in, `reader.offline.enabled`).
 *
 * A service worker that keeps the books a reader saves for offline: the book
 * and chapter pages, the scripts and styles they load, and their images
 * (`/_assets/`). Pages are network-first (fresh when online, the saved copy
 * when not); hashed files (`/_next/static/`, `/_assets/`) are cache-first.
 * Nothing is cached until a reader saves a book.
 *
 * Serve the script from your site's root, for example with Next.js:
 *
 *   // app/zreader-sw.js/route.ts
 *   export { GET } from "zreader/next/sw";   // or: new Response(serviceWorkerScript(), { headers: SW_HEADERS })
 *
 * No Node or DOM APIs: the script is a string.
 */

export const SW_CACHE = "zreader-offline-v1";
export const SW_PATH = "/zreader-sw.js";

/** Messages the page sends to the worker. */
export type ServiceWorkerMessage =
  | { type: "zr:save"; key: string; urls: string[] }
  | { type: "zr:remove"; key: string }
  | { type: "zr:status"; key: string };

/** Replies on the message port. */
export type ServiceWorkerReply =
  | { type: "zr:progress"; done: number; total: number }
  | { type: "zr:saved"; saved: number; failed: number }
  | { type: "zr:removed"; removed: number }
  | { type: "zr:status"; saved: boolean; count: number; savedAt?: string };

export interface ServiceWorkerOptions {
  /** Cache name. Change it to drop every saved book. */
  cacheName?: string;
  /** Extra URL prefixes treated as immutable (cache-first). */
  immutablePrefixes?: string[];
}

export const SW_HEADERS: Record<string, string> = {
  "Content-Type": "text/javascript; charset=utf-8",
  "Cache-Control": "no-cache",
  "Service-Worker-Allowed": "/",
  "X-Content-Type-Options": "nosniff",
};

/** The service worker source. */
export function serviceWorkerScript(options: ServiceWorkerOptions = {}): string {
  const config = JSON.stringify({
    cache: options.cacheName ?? SW_CACHE,
    immutable: ["/_next/static/", "/_next/image", "/_assets/", ...(options.immutablePrefixes ?? [])],
  });
  return `/* zreader offline reading — generated by zreader/sw */
"use strict";
const CONFIG = ${config};
const INDEX = "/__zreader__/index.json";

self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (event) => event.waitUntil(self.clients.claim()));

async function readIndex(cache) {
  const res = await cache.match(INDEX);
  return res ? res.json() : {};
}
async function writeIndex(cache, index) {
  await cache.put(INDEX, new Response(JSON.stringify(index), { headers: { "Content-Type": "application/json" } }));
}

function sameOrigin(url) {
  return new URL(url, self.location.href).origin === self.location.origin;
}

/** Files a saved page needs: its scripts, styles, images and fonts (same origin). */
function dependencies(html, base) {
  const out = new Set();
  const re = /(?:src|href|srcset)=["']([^"']+)["']/gi;
  let m;
  while ((m = re.exec(html))) {
    for (const part of m[1].split(/,\\s+/)) {
      const raw = part.trim().split(/\\s+/)[0];
      if (!raw || raw.startsWith("data:") || raw.startsWith("#")) continue;
      let url;
      try { url = new URL(raw.replace(/&amp;/g, "&"), base); } catch { continue; }
      if (url.origin !== self.location.origin) continue;
      const p = url.pathname;
      if (CONFIG.immutable.some((x) => p.includes(x)) || /\\.(css|js|woff2?|png|jpe?g|gif|webp|avif|svg)$/i.test(p) || p.startsWith("/_next/image")) out.add(url.href);
    }
  }
  return [...out];
}

async function save(key, urls, port) {
  const cache = await caches.open(CONFIG.cache);
  const all = new Set(urls.map((u) => new URL(u, self.location.href).href).filter(sameOrigin));
  let done = 0, saved = 0, failed = 0;
  const queue = [...all];
  const seen = new Set(queue);
  while (queue.length) {
    const url = queue.shift();
    try {
      const res = await fetch(url, { credentials: "same-origin", cache: "no-cache" });
      if (!res.ok) throw new Error(String(res.status));
      if ((res.headers.get("content-type") || "").includes("text/html")) {
        const html = await res.clone().text();
        for (const dep of dependencies(html, url)) if (!seen.has(dep)) { seen.add(dep); queue.push(dep); }
      }
      await cache.put(url, res);
      saved++;
    } catch { failed++; }
    done++;
    port && port.postMessage({ type: "zr:progress", done, total: seen.size });
  }
  const index = await readIndex(cache);
  index[key] = { urls: [...seen], savedAt: new Date().toISOString() };
  await writeIndex(cache, index);
  port && port.postMessage({ type: "zr:saved", saved, failed });
}

async function remove(key, port) {
  const cache = await caches.open(CONFIG.cache);
  const index = await readIndex(cache);
  const entry = index[key];
  delete index[key];
  const keep = new Set(Object.values(index).flatMap((e) => e.urls));
  let removed = 0;
  for (const url of entry ? entry.urls : []) {
    if (keep.has(url)) continue;
    if (await cache.delete(url)) removed++;
  }
  await writeIndex(cache, index);
  port && port.postMessage({ type: "zr:removed", removed });
}

async function status(key, port) {
  const cache = await caches.open(CONFIG.cache);
  const entry = (await readIndex(cache))[key];
  port && port.postMessage({ type: "zr:status", saved: !!entry, count: entry ? entry.urls.length : 0, savedAt: entry && entry.savedAt });
}

self.addEventListener("message", (event) => {
  const msg = event.data || {};
  const port = event.ports && event.ports[0];
  if (typeof msg.key !== "string") return;
  if (msg.type === "zr:save" && Array.isArray(msg.urls)) event.waitUntil(save(msg.key, msg.urls, port));
  else if (msg.type === "zr:remove") event.waitUntil(remove(msg.key, port));
  else if (msg.type === "zr:status") event.waitUntil(status(msg.key, port));
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || !sameOrigin(req.url)) return;
  const url = new URL(req.url);
  if (url.pathname === INDEX) return;
  if (CONFIG.immutable.some((x) => url.pathname.includes(x))) {
    // Cache-first, and only answer from the cache: never store unsaved files.
    // ignoreVary: next/image responses vary on Accept, which differs between the save and an <img>.
    event.respondWith(caches.open(CONFIG.cache).then((c) => c.match(req, { ignoreVary: true })).then((hit) => hit || fetch(req)));
    return;
  }
  if (req.mode === "navigate" || (req.headers.get("accept") || "").includes("text/html") || url.searchParams.has("_rsc") || req.headers.get("rsc")) {
    // Network-first; the saved copy when offline. Saved pages are refreshed as they are read.
    event.respondWith(
      (async () => {
        const cache = await caches.open(CONFIG.cache);
        const saved = await cache.match(req, { ignoreSearch: req.mode === "navigate", ignoreVary: true });
        try {
          const res = await fetch(req);
          if (saved && res.ok && req.mode === "navigate") cache.put(req.url.split("#")[0], res.clone());
          return res;
        } catch (e) {
          if (saved) return saved;
          if (req.mode === "navigate") {
            return new Response("<!doctype html><meta charset=utf-8><title>Offline</title><p style='font:16px system-ui;padding:2rem'>You're offline, and this page wasn't saved for offline reading.</p>", { status: 503, headers: { "Content-Type": "text/html; charset=utf-8" } });
          }
          throw e;
        }
      })(),
    );
  }
});
`;
}
